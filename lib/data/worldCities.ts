// Self-hosted world city/country reference data — backs /api/geo/cities
// (the Admin "Add Destination" and Contributor "Other Destination"
// autocomplete). Deliberately NOT a third-party HTTP API: this app already
// avoids adding paid/rate-limited external dependencies wherever a
// self-hosted alternative works (see lib/googleAuth.ts's own comment on the
// same philosophy), and a bundled dataset is strictly more "reliable for
// global locations" than a live third-party call — no network dependency,
// no API key to configure, no rate limit, no outage risk, and it's faster
// (in-process array scan vs. an outbound HTTP round trip).
//
// Every country's official/capital city is included, plus each major
// tourism/travel-news-relevant country's largest additional cities, so the
// dataset covers the countries and cities this site's contributors and
// admins are realistically going to search for. Country names here are the
// canonical display names used everywhere a city's country is shown or
// slugified (see lib/countries.ts) — the search API and every picker built
// on top of it always returns one of these exact spellings, which is what
// keeps "France" from ever being saved as "france"/"FR"/"French Republic"
// inconsistently across different cities.
